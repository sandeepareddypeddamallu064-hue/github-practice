import java.util.Arrays;
public class CreatingArrays{
    public static void main(String[] args){
        int[] arr = new int[3];
        arr[0] = 1;
        arr[1] = 3;
        arr[2] = 4;
        System.out.println(Arrays.toString(arr));
        //all together
        String sArray[] = {"sammu","anvi"};
        System.out.print(Arrays.toString(sArray));

    }
}